def points_for_table(source: str) -> tuple[BenchmarkPoint, ...]:
    return tuple(item for item in BENCHMARK_POINTS if item.source == source)


def points_for_method(method: str) -> tuple[BenchmarkPoint, ...]:
    return tuple(item for item in BENCHMARK_POINTS if item.method == method)


def point(cohort: str, method: str, metric: str) -> BenchmarkPoint:
    matches = tuple(
        item
        for item in BENCHMARK_POINTS
        if item.cohort == cohort and item.method == method and item.metric == metric
    )
    if len(matches) != 1:
        raise KeyError((cohort, method, metric))
    return matches[0]


def compare_observed(
    observed: float,
    cohort: str,
    method: str,
    metric: str,
    tolerance: float,
) -> float:
    target = point(cohort, method, metric)
    difference = observed - target.value
    if abs(difference) > tolerance:
        raise ValueError(f"observed value differs from target by {difference}")
    return difference
